import { Alert, Button, Divider, Group, Modal, Select, SimpleGrid, Stack, Text, Textarea, TextInput } from "@mantine/core";
import { DateInput } from "@mantine/dates";
import { notifications } from "@mantine/notifications";
import { IconId } from "@tabler/icons-react";
import { useQueryClient } from "@tanstack/react-query";
import { useEffect, useState } from "react";
import { useNavigate } from "react-router";

import { ApiError, errorMessage, post } from "@/api/client";
import { useClasses, useYears } from "@/hooks/useSchool";

type Values = Record<string, string>;

const SECTIONS: { title: string; fields: [string, string, string?][] }[] = [
  {
    title: "Learner",
    fields: [
      ["first_name", "First name *", "e.g. Aisha"],
      ["last_name", "Surname *", "e.g. Namubiru"],
      ["other_names", "Other names"],
      ["lin", "LIN", "Learner Identification Number"],
      ["religion", "Religion", "e.g. Catholic"],
      ["nationality", "Nationality", "Ugandan"],
      ["previous_school", "Previous school"],
    ],
  },
  {
    title: "Home",
    fields: [
      ["district", "District", "e.g. Wakiso"],
      ["address", "Village / address", "e.g. Kazo, Nansana"],
    ],
  },
  {
    title: "Parents and guardian",
    fields: [
      ["father_name", "Father's name"],
      ["father_phone", "Father's phone", "e.g. 0772 123456"],
      ["father_occupation", "Father's occupation"],
      ["mother_name", "Mother's name"],
      ["mother_phone", "Mother's phone", "e.g. 0701 234567"],
      ["mother_occupation", "Mother's occupation"],
      ["guardian_name", "Guardian's name", "If not a parent"],
      ["guardian_relationship", "Guardian relationship", "e.g. Aunt"],
      ["guardian_phone", "Guardian's phone"],
      ["guardian_email", "Guardian's email", "For emailed report cards"],
    ],
  },
  {
    title: "Health (seen only by the nurse and head teacher)",
    fields: [
      ["allergies", "Allergies", "e.g. Penicillin, peanuts"],
      ["medical_conditions", "Illness / medical conditions", "e.g. Asthma"],
      ["special_needs", "Special needs"],
    ],
  },
];

/** Enrol one learner with the same details as a row of the Excel template. The admission
 *  number is generated by the system. */
export function EnrolLearner({ onClose }: { onClose: () => void }) {
  const client = useQueryClient();
  const navigate = useNavigate();
  const { options: yearOptions, current } = useYears();
  const { options: classOptions, streamOptions } = useClasses();
  const [values, setValues] = useState<Values>({ sex: "", residence: "Day", nationality: "Ugandan" });
  const [busy, setBusy] = useState(false);
  const [problem, setProblem] = useState<string | null>(null);
  const set = (key: string) => (value: string | null) => setValues((v) => ({ ...v, [key]: value ?? "" }));
  useEffect(() => {
    if (!values.academic_year && current) set("academic_year")(String(current.id));
  }, [current]); // eslint-disable-line react-hooks/exhaustive-deps
  const streams = streamOptions(values.school_class || null);
  const ready = values.first_name && values.last_name && values.sex && values.school_class && values.academic_year;

  const save = async () => {
    setBusy(true);
    setProblem(null);
    try {
      const result = await post("/learners/enrol/", { ...values, stream: values.stream || null });
      notifications.show({ color: "green", title: `${result.name} enrolled in ${result.class}`, message: `Admission number ${result.adm_no}` });
      client.invalidateQueries({ queryKey: ["list", "/learners/"] });
      client.invalidateQueries({ queryKey: ["classes"] });
      onClose();
      navigate(`/learners/${result.id}`);
    } catch (error) {
      setProblem(error instanceof ApiError && error.data && !error.data.detail ? Object.values(error.data).flat().join(" ") : errorMessage(error));
    } finally {
      setBusy(false);
    }
  };

  return (
    <Modal opened onClose={onClose} title="Enrol a learner" size="xl" centered>
      <Stack>
        <Alert color="blue" icon={<IconId size={18} />}>
          The admission number is given automatically. The form has the same details as the Excel template, so a class can
          also be imported in one go.
        </Alert>
        <SimpleGrid cols={{ base: 1, sm: 3 }}>
          <Select label="Academic year" data={yearOptions} value={values.academic_year || null} onChange={set("academic_year")} required allowDeselect={false} />
          <Select
            label="Class"
            placeholder="e.g. P1"
            data={classOptions}
            value={values.school_class || null}
            onChange={(v) => setValues((x) => ({ ...x, school_class: v ?? "", stream: "" }))}
            searchable
            required
          />
          <Select
            label="Stream"
            placeholder={streams.length ? "Optional, e.g. East" : "No streams"}
            data={streams}
            value={values.stream || null}
            onChange={set("stream")}
            disabled={!streams.length}
            clearable
          />
        </SimpleGrid>
        {SECTIONS.map((section, index) => (
          <Stack key={section.title} gap="xs">
            <Divider label={section.title} labelPosition="left" />
            <SimpleGrid cols={{ base: 1, sm: 3 }}>
              {section.fields.map(([name, label, placeholder]) =>
                name === "medical_conditions" ? (
                  <Textarea key={name} label={label} placeholder={placeholder} value={values[name] ?? ""} onChange={(e) => set(name)(e.currentTarget.value)} autosize minRows={1} />
                ) : (
                  <TextInput key={name} label={label.replace(" *", "")} withAsterisk={label.endsWith("*")} placeholder={placeholder} value={values[name] ?? ""} onChange={(e) => set(name)(e.currentTarget.value)} />
                ),
              )}
              {index === 0 && (
                <>
                  <Select label="Sex" withAsterisk data={[{ value: "F", label: "Female" }, { value: "M", label: "Male" }]} value={values.sex || null} onChange={set("sex")} />
                  <DateInput label="Date of birth" placeholder="Pick a date" value={values.date_of_birth || null} onChange={(v) => set("date_of_birth")(v)} maxDate={new Date()} valueFormat="D MMM YYYY" clearable />
                  <Select label="Day or boarding" data={["Day", "Boarding"]} value={values.residence} onChange={set("residence")} allowDeselect={false} />
                </>
              )}
            </SimpleGrid>
          </Stack>
        ))}
        <Textarea label="Other notes" value={values.notes ?? ""} onChange={(e) => set("notes")(e.currentTarget.value)} autosize minRows={1} />
        {problem && <Alert color="red">{problem}</Alert>}
        <Group justify="space-between">
          <Text size="xs" c="dimmed">* required</Text>
          <Button onClick={save} loading={busy} disabled={!ready}>Enrol learner</Button>
        </Group>
      </Stack>
    </Modal>
  );
}
